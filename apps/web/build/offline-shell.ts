import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';

type ShellAsset = { path: string; sha256: string; contentType: string };
const hash = (value: string | Uint8Array) => createHash('sha256').update(value).digest('hex');

/** This build-only manifest never discovers URLs at runtime. Personal content is not eligible. */
export function offlineShell(): Plugin {
  return {
    name: 'jarvis-public-offline-shell', enforce: 'post', apply: 'build',
    generateBundle(_options, bundle) {
      const html = bundle['offline-capture.html'];
      if (!html || html.type !== 'asset') throw new Error('Offline capture HTML is missing.');
      const htmlText = String(html.source);
      const names = new Set<string>(['offline-capture.html']);
      const visit = (name: string) => {
        if (names.has(name)) return;
        const output = bundle[name];
        if (!output || !name.startsWith('assets/') || name.includes('?') || name.includes('..')) throw new Error(`Invalid offline shell dependency: ${name}`);
        names.add(name);
        if (output.type === 'chunk') {
          for (const child of [...output.imports, ...output.dynamicImports]) visit(child);
          const metadata = (output as typeof output & { viteMetadata?: { importedCss?: Set<string>; importedAssets?: Set<string> } }).viteMetadata;
          for (const child of [...(metadata?.importedCss || []), ...(metadata?.importedAssets || [])]) visit(child);
        }
      };
      // Only references emitted in this independent document are roots of the public cache.
      for (const match of htmlText.matchAll(/(?:src|href)="\/(assets\/[^"?#]+)"/g)) visit(match[1]);
      if (names.size < 2) throw new Error('Offline capture entry was not found.');
      const entries: ShellAsset[] = [...names].sort().map(name => {
        const item = bundle[name];
        const bytes = item.type === 'chunk' ? item.code : item.source;
        return { path: '/' + name, sha256: hash(bytes), contentType: name.endsWith('.html') ? 'text/html; charset=utf-8' : name.endsWith('.js') ? 'text/javascript; charset=utf-8' : name.endsWith('.css') ? 'text/css; charset=utf-8' : 'application/octet-stream' };
      });
      const version = hash('jarvis-offline-static-v1\n' + JSON.stringify(entries));
      const source = serviceWorker(entries, version);
      this.emitFile({ type: 'asset', fileName: 'offline-capture-sw.js', source });
      this.emitFile({ type: 'asset', fileName: 'offline-capture-shell-manifest.json', source: JSON.stringify({ schema: 1, version, scope: '/offline-capture.html', entries }, null, 2) + '\n' });
    },
  };
}

function serviceWorker(entries: ShellAsset[], version: string): string {
  return `/* Public offline capture shell only. Generated by the build; no runtime discovery. */
const ENTRIES = ${JSON.stringify(entries)};
const VERSION = ${JSON.stringify(version)};
const PREFIX = 'jarvis-public-offline-shell-v1:';
const CACHE = PREFIX + VERSION;
const PATHS = new Set(ENTRIES.map(item => item.path));
const digest = async bytes => Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))).map(byte => byte.toString(16).padStart(2, '0')).join('');
async function valid(response, item) {
  return !!response && response.status === 200 && await digest(await response.arrayBuffer()) === item.sha256;
}
async function cacheReady() {
  if (!await caches.has(CACHE)) return false;
  const cache = await caches.open(CACHE);
  const keys = await cache.keys();
  if (keys.length !== ENTRIES.length) return false;
  for (const item of ENTRIES) if (!await valid(await cache.match(new URL(item.path, self.location.origin).href), item)) return false;
  return true;
}
self.addEventListener('install', event => event.waitUntil((async () => {
  // Reusing a complete identical cache is safe; never delete an existing active cache on failure.
  if (await caches.has(CACHE)) {
    if (!await cacheReady()) throw new Error('Existing offline shell is incomplete.');
    return;
  }
  const cache = await caches.open(CACHE);
  try {
    for (const item of ENTRIES) {
      const url = new URL(item.path, self.location.origin);
      const response = await fetch(new Request(url.href, { cache: 'no-store', credentials: 'omit', redirect: 'error' }));
      if (response.url !== url.href || !await valid(response.clone(), item)) throw new Error('Offline shell fingerprint mismatch.');
      const bytes = await response.arrayBuffer();
      await cache.put(url.href, new Response(bytes, { status: 200, headers: { 'Content-Type': item.contentType } }));
    }
    if (!await cacheReady()) throw new Error('Offline shell did not finish caching.');
  } catch (error) { await caches.delete(CACHE); throw error; }
})()));
// No skipWaiting: an open editing page keeps its current shell until it closes.
self.addEventListener('activate', event => event.waitUntil((async () => {
  if (!await cacheReady()) throw new Error('Offline shell is not ready.');
  for (const name of await caches.keys()) if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
  await self.clients.claim();
})()));
self.addEventListener('message', event => {
  if (event.data?.type !== 'OFFLINE_SHELL_STATUS' || !event.ports[0]) return;
  event.waitUntil(cacheReady().then(ready => event.ports[0].postMessage({ type: 'OFFLINE_SHELL_READY', ready, version: VERSION })).catch(() => event.ports[0].postMessage({ type: 'OFFLINE_SHELL_READY', ready: false })));
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || url.search || !PATHS.has(url.pathname)) return;
  // Exact immutable build allowlist only. API, rooms, platform HTML and unknown requests pass through.
  event.respondWith(caches.open(CACHE).then(cache => cache.match(url.href)).then(response => response || new Response('Offline shell is unavailable. Reconnect to prepare it again.', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } })));
});
`;
}
